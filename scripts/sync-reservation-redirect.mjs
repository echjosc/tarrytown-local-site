// Runs before every build. The /reservations short link used to be a hardcoded
// URL in netlify.toml, which meant updating the reservation provider required a
// code change. Business Info in Keystatic is now the single source of truth —
// this writes that URL into public/_redirects so Netlify picks it up at deploy
// time, same as any other content edit.
import { writeFile } from 'node:fs/promises';
import { createReader } from '@keystatic/core/reader';
import keystaticConfig from '../keystatic.config.ts';

const OUTPUT_PATH = new URL('../public/_redirects', import.meta.url);

const reader = createReader(process.cwd(), keystaticConfig);
const businessInfo = await reader.singletons.businessInfo.read();
const reservationUrl = businessInfo?.reservationUrl?.trim();

if (!reservationUrl || reservationUrl === '#') {
	console.warn('[sync-reservation-redirect] No Reservation URL set in Business Info — skipping /reservations redirect.');
	process.exit(0);
}

const contents = `# Generated by scripts/sync-reservation-redirect.mjs — do not edit by hand.
# Source: Business Info > Reservation URL (Keystatic)
/reservations   ${reservationUrl}   302
`;

await writeFile(OUTPUT_PATH, contents);
console.log(`[sync-reservation-redirect] /reservations -> ${reservationUrl}`);
